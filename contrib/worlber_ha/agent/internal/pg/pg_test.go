package pg

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestLSN(t *testing.T) {
	v, err := ParseLSN("1/0000A0F8")
	if err != nil || v != 1<<32|0xA0F8 {
		t.Fatalf("ParseLSN: %x %v", v, err)
	}
	if FormatLSN(v) != "1/0000A0F8" {
		t.Fatal(FormatLSN(v))
	}
	if _, err := ParseLSN("bogus"); err == nil {
		t.Fatal("expected error")
	}
}

func TestSetAutoConf(t *testing.T) {
	dir := t.TempDir()
	l := &Local{PGData: dir}
	path := filepath.Join(dir, "postgresql.auto.conf")
	os.WriteFile(path, []byte("# Do not edit this file manually!\nport = '5432'\nwork_mem = '4MB'\nsynchronous_standby_names = 'x'\n"), 0600)
	port := "6000"
	ci := "host='a' password='it\\'s'"
	if err := l.SetAutoConf(map[string]*string{"port": &port, "primary_conninfo": &ci, "synchronous_standby_names": nil}); err != nil {
		t.Fatal(err)
	}
	b, _ := os.ReadFile(path)
	s := string(b)
	for _, want := range []string{"port = '6000'", "work_mem = '4MB'", "primary_conninfo = 'host=''a'' password=''it\\''s'''"} {
		if !strings.Contains(s, want) {
			t.Errorf("missing %q in:\n%s", want, s)
		}
	}
	if strings.Contains(s, "synchronous_standby_names") || strings.Count(s, "port =") != 1 {
		t.Errorf("bad result:\n%s", s)
	}
}

func TestConnInfo(t *testing.T) {
	got := ConnInfo("host", "h", "password", `p'w\`, "empty", "")
	if got != `host='h' password='p\'w\\'` {
		t.Fatal(got)
	}
}
